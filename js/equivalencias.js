function renderTabla() {
    const tbodyEq = document.getElementById("tabla-equivalencias");
    const tbodyDet = document.getElementById("tabla-detectados");
    
    if (tbodyEq) tbodyEq.innerHTML = "";
    if (tbodyDet) tbodyDet.innerHTML = "";

    equivalencias.forEach(eq => {
        // Render Tabla Superior (Lista Completa)
        if (tbodyEq) {
            const tr = document.createElement("tr");
            tr.innerHTML = `
                <td><strong>${eq.id}</strong></td>
                <td>${eq.antiguo}</td>
                <td>${eq.oficial}</td>
            `;
            tbodyEq.appendChild(tr);
        }

        // Render Tabla Inferior (Estado de Corrección)
        if (tbodyDet) {
            const esCorregido = eq.antiguo !== eq.oficial;
            const tr = document.createElement("tr");
            tr.innerHTML = `
                <td><strong>${eq.id}</strong></td>
                <td>${eq.antiguo}</td>
                <td><strong>${eq.oficial}</strong></td>
                <td>
                    <span style="padding: 4px 8px; border-radius: 4px; font-size: 0.8em; font-weight: bold; background: ${esCorregido ? '#d1e7dd' : '#f8f9fa'}; color: ${esCorregido ? '#0f5132' : '#6c757d'};">
                        ${esCorregido ? '✏️ Corregido' : '⚪ Sin cambios / Nuevo'}
                    </span>
                </td>
            `;
            tbodyDet.appendChild(tr);
        }
    });
}

function guardarEquivalencia() {
    let antiguo = document.getElementById("historial-antiguo").value.trim();
    let oficial = document.getElementById("nick-oficial").value.trim();
    
    if (!antiguo && !oficial) {
        alert("Por favor ingresa al menos un nombre.");
        return;
    }

    if (!antiguo) antiguo = oficial;
    if (!oficial) oficial = antiguo;

    const existente = equivalencias.find(e => e.antiguo.toLowerCase() === antiguo.toLowerCase());
    
    if (existente) {
        existente.oficial = oficial;
    } else {
        const nuevoId = equivalencias.length > 0 ? Math.max(...equivalencias.map(e => e.id)) + 1 : 1;
        equivalencias.push({ id: nuevoId, antiguo: antiguo, oficial: oficial });
    }
    
    document.getElementById("historial-antiguo").value = "";
    document.getElementById("nick-oficial").value = "";
    renderTabla();
}

function eliminarEquivalencia() {
    const id = parseInt(document.getElementById("id-borrar").value);
    if (isNaN(id)) {
        alert("Ingresa un ID válido.");
        return;
    }
    
    equivalencias = equivalencias.filter(e => e.id !== id);
    document.getElementById("id-borrar").value = "";
    renderTabla();
}

// Ejecución garantizada al cargar la página o script
if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", renderTabla);
} else {
    renderTabla();
}
